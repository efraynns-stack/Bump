// Generates the single file Kino loads; Node is only used during development.
import { readFileSync, writeFileSync } from "node:fs";
const here = new URL("./", import.meta.url);
const catalog = JSON.parse(readFileSync(new URL("catalog.json", here), "utf8"));
const keys = new Set();
for (const episode of catalog.episodes) {
  const key = episode.season + ":" + episode.number;
  if (keys.has(key) || !Number.isInteger(episode.season) || !Number.isInteger(episode.number) ||
      !/^[a-z0-9]{12}$/.test(episode.videoCode)) throw new Error("Invalid episode: " + key);
  keys.add(key);
}
catalog.episodes.sort((a, b) => a.season - b.season || a.number - b.number);
writeFileSync(new URL("plugin.js", here), "// Generated by build.mjs. Edit src/plugin.js and catalog.json.\n" +
  "const CATALOG = " + JSON.stringify(catalog) + ";\n\n" + readFileSync(new URL("src/plugin.js", here), "utf8"));
